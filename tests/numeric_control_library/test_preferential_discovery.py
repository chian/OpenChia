SCOPE = (("assessment", "fixture"),)


def _observe_counts(counts, statuses=None):
    estimator = joint_preferential_discovery(scope_path=SCOPE, epoch="fixture")
    statuses = statuses or [source.OBSERVATION_OBSERVED] * len(counts)
    for index, (count, status) in enumerate(zip(counts, statuses)):
        estimator.observe(
            f"attempt:{index}",
            tuple(f"result:{index}:{item}" for item in range(count)),
            observation_status=status,
        )
        estimator.snapshot()
    return estimator


def _assert_equivalent(actual, expected):
    if isinstance(expected, dict):
        assert actual.keys() == expected.keys()
        for name in expected:
            _assert_equivalent(actual[name], expected[name])
    elif isinstance(expected, list):
        assert len(actual) == len(expected)
        for left, right in zip(actual, expected):
            _assert_equivalent(left, right)
    elif isinstance(expected, float):
        assert actual == pytest.approx(expected, rel=1e-9, abs=1e-10)
    else:
        assert actual == expected


def test_every_transition_matches_reports_from_the_pinned_upstream_program():
    # This independent numerical fixture was generated by executing the pinned
    # upstream file, not by the transferred implementation. No network needed.
    fixture = json.loads(
        (Path(__file__).parent / "fixtures" / "preferential_upstream.json").read_text(
            encoding="utf-8"
        )
    )
    for scenario in fixture["scenarios"]:
        schema = PreferentialChannelSchema(**{
            **scenario["schema"],
            "base_channels": tuple(scenario["schema"]["base_channels"]),
            "union_members": tuple(scenario["schema"]["union_members"]),
            "controller_channels": tuple(scenario["schema"]["controller_channels"]),
        })
        controller = compose_preferential_controller(
            epoch="fixture",
            channel_schema=schema,
            control=PreferentialControllerConfig.uniform(
                tuple(schema.controller_channels), gamma=0.01
            ),
        )(SCOPE)
        _assert_equivalent(controller.state().as_record(), scenario["initial"])
        for observation, expected in zip(scenario["observations"], scenario["steps"]):
            value = PreferentialIncidenceObservation.from_record(observation["value"])
            step = controller.observe(
                observation["label"], value, is_root=scenario["is_root"]
            )
            _assert_equivalent(step.as_record(), expected)
        _assert_equivalent(controller.state().as_record(), scenario["final"])


def test_attempt_order_affects_forecast_even_with_identical_total_discoveries():
    declining = _observe_counts([5, 5, 4, 4, 3, 2, 1, 0, 0, 0])
    rising = _observe_counts([0, 0, 0, 1, 2, 3, 4, 4, 5, 5])
    left, right = declining.snapshot(), rising.snapshot()
    assert left.observed_results == right.observed_results
    assert left.incidence_samples == right.incidence_samples
    assert (
        left.control_statistics["expected_next_discoveries"].value
        < right.control_statistics["expected_next_discoveries"].value
    )


def test_failures_are_jointly_modelled_and_not_recorded_as_observed_zeros():
    counts = [4, 3, 0, 2, 0, 1, 0, 0, 0, 0]
    statuses = [
        source.OBSERVATION_OBSERVED if index % 2 == 0 else source.OBSERVATION_FAILED
        for index in range(len(counts))
    ]
    estimator = _observe_counts(counts, statuses)
    measured = estimator.snapshot()
    assert measured.diagnostics["attempted_units"] == len(counts)
    assert measured.diagnostics["observed_units"] == statuses.count(
        source.OBSERVATION_OBSERVED
    )
    assert measured.diagnostics["failed_units"] == statuses.count(
        source.OBSERVATION_FAILED
    )
    assert measured.diagnostics["failure_yield_coupling_identifiable"] == 1
    observed_zeros = _observe_counts([
        count if status == source.OBSERVATION_OBSERVED else 0
        for count, status in zip(counts, statuses)
    ]).snapshot()
    assert measured.control_statistics != observed_zeros.control_statistics


def test_repeat_identity_is_not_new_and_excluded_attempt_does_not_advance_fit_rank():
    estimator = _observe_counts([3, 2, 1, 1, 0, 0, 0, 0])
    prior = estimator.snapshot()
    estimator.observe("excluded", (), observation_status=source.OBSERVATION_EXCLUDED)
    after = estimator.snapshot()
    assert after.diagnostics["attempted_units"] == prior.diagnostics["attempted_units"]
    assert (
        after.diagnostics["excluded_units"] == prior.diagnostics["excluded_units"] + 1
    )
    repeat = estimator.observe(
        "repeat", ("result:0:0",), observation_status=source.OBSERVATION_OBSERVED
    )
    assert not repeat.new_identities
    assert repeat.repeat_identities == ("result:0:0",)
    assert estimator.snapshot().observed_results.value == prior.observed_results.value


def test_factory_and_epoch_transition_keep_independent_histories():
    schema = PreferentialChannelSchema.single()
    factory = compose_preferential_controller(
        epoch="first",
        channel_schema=schema,
        control=PreferentialControllerConfig.uniform(("overall",), gamma=0),
    )
    parent = factory((("parent", "one"),))
    child = factory((("parent", "one"), ("child", "two")))
    value = PreferentialIncidenceObservation(("identity:one",))
    parent.observe("child-return", value, is_root=True)
    assert parent.report().primary.observed_results.value == 1
    assert child.report().primary.observed_results.value == 0
    child.observe("leaf", value, is_root=False)
    assert parent.report().primary.incidence_samples == 1
    transitioned = parent.transitioned("second")
    assert transitioned.report().primary.observed_results.value == 0
    assert parent.report().primary.observed_results.value == 1
    assert transitioned.epoch == "second"


@dataclass(frozen=True)
class _Result(ClosedRecord):
    units: int

    def as_record(self):
        return {"units": self.units}


class _Source:
    def __init__(self):
        self.index = 0

    def next(self, view):
        if self.index == 10:
            return None
        index = self.index
        self.index += 1
        return Leaf(
            unit=index,
            extract=lambda value: value,
            result=lambda unit, value: PreferentialIncidenceObservation((
                f"identity:{value}",
            )),
            label=f"unit:{index}",
        )


def test_registered_composition_runs_inside_the_real_episode_loop():
    factory = COMPOSE_PREFERENTIAL_CONTROLLER.load()(
        epoch="actual-loop",
        channel_schema=PreferentialChannelSchema.single(),
        control=PreferentialControllerConfig.uniform(("overall",), gamma=0),
    )
    grain = Grain(
        "assessment",
        "one evidence acquisition",
        "accepted evidence identities",
        factory,
    )
    goal = EpisodeGoal.for_grain(grain, objective={"task": "fixture"})
    episode = Episode(
        grain=grain,
        key="fixture",
        source=_Source(),
        request=EpisodeRequest(goal, _Result(0)),
        build_result=lambda record: _Result(record.units_consumed),
    )
    record = episode.run(Context(tree=EpisodeTree(grain), run_id="preferential-loop"))
    assert record.units_consumed == 10
    assert record.controller_state.report.primary.incidence_samples == 10
    assert record.controller_state.report.primary.scope_path == record.path
    assert (
        record.controller_state.report.primary.expected_results.status_code
        == source.STATUS_NORMAL
    )
    assert all(
        isinstance(unit.controller_input, ClosedRecord) for unit in record.unit_records
    )
    json.dumps(record.as_record())


def test_child_returns_are_one_parent_observation_and_do_not_pool_child_histories():
    factory = compose_preferential_controller(
        epoch="nested-loop",
        channel_schema=PreferentialChannelSchema.single(),
        control=PreferentialControllerConfig.uniform(("overall",), gamma=0),
    )
    parent_grain = Grain(
        "assessment", "one completed reader", "accepted identities", factory
    )
    child_grain = Grain("reader", "one document window", "accepted identities", factory)
    parent_goal = EpisodeGoal.for_grain(parent_grain, objective={"task": "nested"})

    def child_result(record):
        identities = tuple(
            dict.fromkeys(
                identity
                for unit in record.unit_records
                for identity in unit.controller_input.identities
            )
        )
        return PreferentialIncidenceObservation(identities)

    children = [
        Episode(
            grain=child_grain,
            key=f"reader:{index}",
            source=_Source(),
            request=EpisodeRequest(
                EpisodeGoal.for_grain(
                    child_grain, parent=parent_goal, objective={"reader": index}
                ),
                _Result(0),
                ReportContract(
                    "Choose the next reader",
                    {},
                    {"identities": "Number of accepted identities"},
                ),
            ),
            build_result=child_result,
        )
        for index in range(2)
    ]

    class ParentSource:
        def __init__(self):
            self.remaining = iter(children)

        def next(self, view):
            child = next(self.remaining, None)
            if child is None:
                return None
            return ChildEpisodeUnit(
                child,
                receive_result=lambda result, completion, request: result,
                synthesize_report=lambda result, completion, request: {
                    "identities": len(result.identities)
                },
            )

    parent = Episode(
        grain=parent_grain,
        key="assessment",
        source=ParentSource(),
        request=EpisodeRequest(parent_goal, _Result(0)),
        build_result=lambda record: _Result(record.units_consumed),
    )
    record = parent.run(
        Context(
            tree=EpisodeTree(parent_grain, {parent_grain: (child_grain,)}),
            run_id="nested-preferential",
        )
    )
    report = record.controller_state.report.primary
    assert report.incidence_samples == 2
    assert (
        report.observed_results.value == 10
    )  # Repeated evidence remains one identity.
    assert report.expected_results.status_code == source.STATUS_INSUFFICIENT
    for unit in record.unit_records:
        child = unit.child.controller_state.report.primary
        assert child.incidence_samples == 10
        assert child.expected_results.status_code == source.STATUS_NORMAL
        assert child.scope_path != report.scope_path
    assert record.unit_records[1].controller_step.unit_yield.new_identities == ()
    json.dumps(record.as_record())


